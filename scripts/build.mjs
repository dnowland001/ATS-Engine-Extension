/*
 * Builds an extension into dist/<app> (21 Oct 2026).
 *
 *   node scripts/build.mjs                    # both extensions, production
 *   node scripts/build.mjs --env=local        # both, local dev servers
 *   node scripts/build.mjs --app=seeker --zip # one, plus a store zip
 *
 * The shared core is copied in beside each app as ./core, with a
 * generated core/config.js holding the ATS Engine addresses, and the
 * manifest's host permission and app address are filled in from the same
 * place - so a build can only ever talk to the one ATS Engine it was
 * built for. No bundler, no minifying: what is in dist is readable and
 * is what the Chrome Web Store / Edge Add-ons reviewers see.
 */
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const arg = (name, fallback) => {
  const hit = process.argv.find((a) => a.startsWith(`--${name}=`));
  return hit ? hit.split('=').slice(1).join('=') : fallback;
};

export const ENVS = {
  production: { apiBase: 'https://api.ats-engine.com/api/v1', appBase: 'https://app.ats-engine.com' },
  local: { apiBase: 'http://localhost:8000/api/v1', appBase: 'http://localhost:5173' },
};

export function build({ app = 'recruiter', env = 'production', out } = {}) {
  const cfg = ENVS[env];
  if (!cfg) throw new Error(`Unknown env "${env}" - use ${Object.keys(ENVS).join(' or ')}.`);
  const src = join(root, 'apps', app);
  if (!existsSync(src)) throw new Error(`No app "${app}" in apps/.`);
  const dest = out || join(root, 'dist', app);

  rmSync(dest, { recursive: true, force: true });
  mkdirSync(dest, { recursive: true });

  cpSync(src, dest, { recursive: true, filter: (p) => !p.endsWith('manifest.template.json') });
  cpSync(join(root, 'packages', 'core'), join(dest, 'core'), { recursive: true });
  mkdirSync(join(dest, 'icons'), { recursive: true });
  for (const s of [16, 32, 48, 128]) cpSync(join(root, 'assets', `icon-${s}.png`), join(dest, 'icons', `icon-${s}.png`));
  cpSync(join(root, 'assets', 'logo.png'), join(dest, 'logo.png'));

  writeFileSync(
    join(dest, 'core', 'config.js'),
    `/* Generated by scripts/build.mjs (${env}) - do not edit. */\nexport const CONFIG = Object.freeze(${JSON.stringify({ env, ...cfg }, null, 2)});\n`,
  );

  const manifest = readFileSync(join(src, 'manifest.template.json'), 'utf8')
    .replaceAll('__API_ORIGIN__', new URL(cfg.apiBase).origin)
    .replaceAll('__APP_ORIGIN__', new URL(cfg.appBase).origin);
  const parsed = JSON.parse(manifest);
  if (env !== 'production') parsed.name += ` (${env})`;
  writeFileSync(join(dest, 'manifest.json'), JSON.stringify(parsed, null, 2) + '\n');

  return { dest, manifest: parsed };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const which = arg('app', 'all');
  const env = arg('env', 'production');
  const apps = which === 'all' ? ['recruiter', 'seeker'] : [which];
  for (const app of apps) {
    const { dest, manifest } = build({ app, env });
    console.log(`Built ${manifest.name} ${manifest.version} -> ${dest}`);
    if (process.argv.includes('--zip')) {
      const zip = join(root, 'dist', `ats-engine-${app}-${manifest.version}${env === 'production' ? '' : '-' + env}.zip`);
      rmSync(zip, { force: true });
      execFileSync('zip', ['-qr', zip, '.'], { cwd: dest });
      console.log(`Zipped -> ${zip}`);
    }
  }
}
